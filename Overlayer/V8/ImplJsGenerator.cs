    public static bool IsValidIdentifier(string name) {
        if (string.IsNullOrEmpty(name)) {
            return false;
        }
        if (!(char.IsLetter(name[0]) || name[0] == '_' || name[0] == '$')) {
            return false;
        }
        return name.Skip(1).All(c => char.IsLetterOrDigit(c) || c == '_' || c == '$');
    }

    public static bool IsReservedGlobal(string name)
        => name is "Tag" or "Store" or "RegisterTag" or "TagType";

    public static string SanitizeParamName(string name, int index = -1) {
        if (IsValidIdentifier(name)) {
            return name;
        }
        return index >= 0 ? $"arg{index + 1}" : "arg";
    }

    public static string EscapeDocComment(string value)
        => value.Replace("*/", "* /");

    public static string MapToJsType(Type type) {
        if (type == typeof(int) || type == typeof(float) || type == typeof(double) || type == typeof(long) ||
            type == typeof(byte) || type == typeof(short) || type == typeof(uint) || type == typeof(ulong) ||
            type == typeof(ushort) || type == typeof(decimal)) {
            return "number";
        }

        if (type == typeof(string) || type.IsEnum) {
            return "string";
        }

        if (type == typeof(bool)) {
            return "boolean";
        }

        return "any";
    }
